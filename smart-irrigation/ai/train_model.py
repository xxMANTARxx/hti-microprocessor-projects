"""
Train the AI model for the Smart Irrigation project.

Model: Decision Tree classifier (scikit-learn).
Inputs : tray_level (%), tds (ppm), temp (C), humidity (%), light (%, from the LDR)
Output : 0 = WAIT, 1 = IRRIGATE, 2 = ALERT (water too salty for the plant)

Training data:
  1) Synthetic samples labeled by agriculture rules
     (FAO irrigation water salinity guide: < 450 ppm = no problem,
      above that the risk grows. Our TDS sensor (TDS Meter V1.0) only reads up to
      about 1000 ppm, so we use a limit for a salt-sensitive house plant:
      > 800 ppm = too salty -> do not irrigate).
  2) OPTIONAL: your own readings. Put them in my_readings.csv with columns
     tray_level,tds,temp,humidity,light,label   (label = 0, 1 or 2)
     The ESP32 prints readings in this format on the Serial Monitor.

Run:  pip install scikit-learn numpy   then   python train_model.py
It prints the accuracy and a C function. Paste that function into smart_irrigation.ino
(replace the old aiDecide function).
"""
import os
import numpy as np
from sklearn.tree import DecisionTreeClassifier, export_text
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score, classification_report

rng = np.random.default_rng(42)
N = 6000
FEATURES = ["tray_level", "tds", "temp", "humidity", "light"]
SALT_LIMIT = 800   # ppm
STRONG_SUN = 70    # light %: strong midday sun
EMERGENCY = 15     # level %: so dry that we water even in strong sun


def rule_label(level, tds, temp, hum, light):
    if tds > SALT_LIMIT:                # water too salty: never irrigate
        return 2
    need_at = 40                         # irrigate when tray level is below this %
    if temp > 30 or hum < 40:            # hot or dry air: plants drink more, water earlier
        need_at = 55
    elif temp < 18:                      # cold: plants drink less
        need_at = 30
    if light > STRONG_SUN and level >= EMERGENCY:   # strong sun: water evaporates fast,
        return 0                                   # wait for softer light (unless very dry)
    return 1 if level < need_at else 0


level = rng.uniform(0, 100, N)
tds = np.concatenate([rng.uniform(0, 800, N // 2), rng.uniform(0, 1200, N - N // 2)])
temp = rng.uniform(10, 42, N)
hum = rng.uniform(15, 95, N)
light = rng.uniform(0, 100, N)
X = np.column_stack([level, tds, temp, hum, light])
y = np.array([rule_label(*row) for row in X])

# sensor noise: flip 2% of labels so the tree does not just memorise the rules
flip = rng.random(N) < 0.02
y[flip] = rng.integers(0, 3, flip.sum())

if os.path.exists("my_readings.csv"):
    real = np.genfromtxt("my_readings.csv", delimiter=",", skip_header=1)
    real = real.reshape(-1, 6)
    X = np.vstack([X, np.repeat(real[:, :5], 5, axis=0)])   # real data counts 5x
    y = np.concatenate([y, np.repeat(real[:, 5].astype(int), 5)])
    print(f"Added {len(real)} real readings")

X_tr, X_te, y_tr, y_te = train_test_split(X, y, test_size=0.25, random_state=1, stratify=y)
model = DecisionTreeClassifier(max_depth=6, min_samples_leaf=20, random_state=1)
model.fit(X_tr, y_tr)
pred = model.predict(X_te)
print(f"Test accuracy: {accuracy_score(y_te, pred) * 100:.1f}%")
print(classification_report(y_te, pred, target_names=["WAIT", "IRRIGATE", "ALERT"]))
print(export_text(model, feature_names=FEATURES))


def to_c(tree):
    t = tree.tree_
    lines = []

    def rec(node, depth):
        pad = "  " * depth
        if t.children_left[node] == -1:
            lines.append(f"{pad}return {int(np.argmax(t.value[node]))};")
            return
        f = FEATURES[t.feature[node]]
        lines.append(f"{pad}if ({f} <= {t.threshold[node]:.2f}f) {{")
        rec(t.children_left[node], depth + 1)
        lines.append(f"{pad}}} else {{")
        rec(t.children_right[node], depth + 1)
        lines.append(f"{pad}}}")

    rec(0, 1)
    return ("// Trained decision tree (generated by train_model.py)\n"
            "// returns 0 = WAIT, 1 = IRRIGATE, 2 = ALERT\n"
            "int aiDecide(float tray_level, float tds, float temp, float humidity, float light) {\n"
            + "\n".join(lines) + "\n}\n")


c_code = to_c(model)
with open("ai_model.h", "w") as f:
    f.write(c_code)
print("\n----- C code (also saved to ai_model.h) -----\n")
print(c_code)
